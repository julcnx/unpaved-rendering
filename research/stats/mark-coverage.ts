// Where can the Off-road mark be used today? Per country, the share of Unpaved km that has `smoothness`
// `tracktype` or `4wd_only` (any value), from the tag-combination tables (no extract needed).
// Usage: node stats/mark-coverage.ts > stats/mark-coverage.md

import { readdirSync, readFileSync } from 'node:fs';
import { classifyDetailed } from '../classifier/classify.ts';

type Combos = { country: string; data_date: string; keys: string[]; combos: [(string | null)[], number][] };
const nameOf = (code: string) => JSON.parse(readFileSync(new URL(`./results/${code}.json`, import.meta.url), 'utf8')).name as string;

const rows = readdirSync(new URL('./combos/', import.meta.url)).filter((f) => f.endsWith('.json')).map((f) => {
  const c: Combos = JSON.parse(readFileSync(new URL(`./combos/${f}`, import.meta.url), 'utf8'));
  let unpaved = 0, evidence = 0, smooth = 0, track = 0, fourWd = 0, mark = 0;
  for (const [values, km] of c.combos) {
    const tags = Object.fromEntries(c.keys.map((k, i) => [k, values[i] ?? undefined]));
    const r = classifyDetailed(tags);
    if (r.base !== 'unpaved') continue;
    unpaved += km;
    if (tags.smoothness) smooth += km;
    if (tags.tracktype) track += km;
    if (tags['4wd_only']) fourWd += km;
    if (tags.smoothness || tags.tracktype || tags['4wd_only']) evidence += km;
    if (r.mark) mark += km;
  }
  return { code: c.country, name: nameOf(c.country), unpaved, evidence, smooth, track, fourWd, mark };
}).filter((r) => r.code !== 'aq' && r.unpaved > 0).sort((a, b) => b.evidence / b.unpaved - a.evidence / a.unpaved);

// Short table for the article: the screenshot-spot countries in the stats (Canada is on hold), plus Brazil (most Unpaved km).
const ARTICLE = ['bo', 'is', 'np', 'na', 'au', 'br'];
const pct = (a: number, b: number) => (b ? (100 * a / b).toFixed(1) : '0.0');
const km = (n: number) => Math.round(n).toLocaleString('en-US');
const total = rows.reduce((t, r) => ({ unpaved: t.unpaved + r.unpaved, evidence: t.evidence + r.evidence, mark: t.mark + r.mark }), { unpaved: 0, evidence: 0, mark: 0 });

console.log(`# Off-road mark: where is the evidence today?

Generated by \`stats/mark-coverage.ts\` from \`stats/combos/\` (${rows.length} countries, Antarctica excluded). Road classes as in the stats (motorway to residential).

Evidence = \`smoothness\`, \`tracktype\` or \`4wd_only\` present (any value) on an Unpaved road: only there can the Off-road mark be decided. Off-road = Unpaved km that get the mark (better \`smoothness\` or \`tracktype=grade2\` give no mark).

All countries: ${km(total.unpaved)} Unpaved km, **${pct(total.evidence, total.unpaved)}% with evidence**, ${pct(total.mark, total.unpaved)}% with the Off-road mark.

## Short table for the article

| Country | Unpaved km | With evidence | Off-road mark |
|---|---:|---:|---:|
${ARTICLE.map((code) => rows.find((r) => r.code === code)!).map((r) => `| ${r.name} | ${km(r.unpaved)} | ${pct(r.evidence, r.unpaved)}% | ${pct(r.mark, r.unpaved)}% |`).join('\n')}

## All countries

| Country | Unpaved km | With evidence | \`smoothness\` | \`tracktype\` | \`4wd_only\` | Off-road mark |
|---|---:|---:|---:|---:|---:|---:|`);
for (const r of rows) console.log(`| ${r.name} | ${km(r.unpaved)} | ${pct(r.evidence, r.unpaved)}% | ${pct(r.smooth, r.unpaved)}% | ${pct(r.track, r.unpaved)}% | ${pct(r.fourWd, r.unpaved)}% | ${pct(r.mark, r.unpaved)}% |`);
