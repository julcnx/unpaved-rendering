// Copies the style values from the osm-wiki mockups (the single source) into js/style-spec.js.
// Usage: node scripts/sync-styles.mjs [path/to/styles.json]
// Default source: ../osm-wiki/unpaved-rendering/mockups/styles.json (written by make-mockups.ts there).
import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2] ?? new URL('../../osm-wiki/unpaved-rendering/mockups/styles.json', import.meta.url);
const spec = JSON.parse(readFileSync(src, 'utf8'));
writeFileSync(new URL('../js/style-spec.js', import.meta.url),
  `// Generated by scripts/sync-styles.mjs from ${spec.source}. Do not edit: change the mockups and sync again.\nexport default ${JSON.stringify(spec, null, 2)};\n`);
console.log(`js/style-spec.js: ${Object.keys(spec.classes).length} classes, ${Object.keys(spec.styles).length} styles`);
